# 未命中品类时的兜底
DEFAULT_CATEGORY = "其他"


@dataclass
class DrugClass:
    name: str
    is_otc: bool
    category: str
    rx_signal: str = ""           # 命中的处方药信号词（空=未命中）
    confidence: str = "low"      # high / medium / low

    @property
    def label(self) -> str:
        return "处方药" if not self.is_otc else "非处方药(OTC)"


def classify(name: str) -> DrugClass:
    """对药品名做处方药与品类分类。"""
    lowered = (name or "").strip().lower()

    # 1) 处方药判定（最长关键词优先，命中即处方药）
    rx_signal = ""
    best_len = 0
    for kw in RX_SIGNALS:
        if kw.lower() in lowered and len(kw) > best_len:
            rx_signal = kw
            best_len = len(kw)
    is_otc = rx_signal == ""

    # 2) 品类判定（最长关键词优先，避免“阿司匹林肠溶”被“阿司匹林”抢匹配）
    category = DEFAULT_CATEGORY
    best_len = 0
    for cat, keywords in CATEGORY_KB:
        for kw in keywords:
            if kw.lower() in lowered and len(kw) > best_len:
                category = cat
                best_len = len(kw)

    # 3) 置信度：命中明确信号为 high/medium，未收录为 low
    if rx_signal:
        confidence = "high"
    elif category != DEFAULT_CATEGORY:
        confidence = "medium"
    else:
        confidence = "low"

    return DrugClass(
        name=name or "",
        is_otc=is_otc,
        category=category,
        rx_signal=rx_signal,
        confidence=confidence,
    )